import {loadPyodide} from 'pyodide';
import fs from 'node:fs/promises';
import path from 'node:path';
const py=await loadPyodide({indexURL:path.resolve('public/runtime')+'/'});
await py.loadPackage(['micropip','pillow','cryptography']);
const wheels=JSON.parse(await fs.readFile('public/wheels.json','utf8'));
py.globals.set('wheel_urls',wheels.map(file=>'http://127.0.0.1:8767/wheels/'+file));
await py.runPythonAsync('import micropip\nawait micropip.install(wheel_urls.to_py(),deps=False)');
for(const file of ['analyzer.py','browser_bridge.py'])py.FS.writeFile('/home/pyodide/'+file,await fs.readFile('public/'+file,'utf8'));
py.runPython('from browser_bridge import execute');
const folder=process.env.LABOR_CARD_FIXTURES;if(!folder)throw Error('Set LABOR_CARD_FIXTURES to a folder of labor-card PDFs.');
const files=await Promise.all((await fs.readdir(folder)).filter(x=>x.endsWith('.pdf')).map(async name=>({name,data:(await fs.readFile(folder+'/'+name)).toString('base64')})));
py.globals.set('payload',JSON.stringify({action:'analyze',files,settings:{}}));
const result=JSON.parse(py.runPython('execute(payload)'));
await fs.writeFile('browser-test-results.json',JSON.stringify(result));
console.log(result.documents.map(d=>d.cards.map(c=>({date:c.date,rows:c.rows.length,findings:c.findings.length,positives:c.positives.length}))).flat());
py.globals.set('payload',JSON.stringify({action:'export',settings:{}}));
const pdf=Buffer.from(py.runPython('execute(payload)'),'base64');
if(!pdf.subarray(0,4).equals(Buffer.from('%PDF')))throw Error('Invalid export');
await fs.writeFile('browser-test-export.pdf',pdf);
console.log('Browser export validated: '+pdf.length+' bytes');
const friday=result.documents.findIndex(d=>d.cards[0].date==='October 9, 2026');
const card=result.documents[friday].cards[0];
const manager=card.rows.find(r=>r.role==='Manager');
const server=card.rows.find(r=>r.role==='Server');
py.globals.set('payload',JSON.stringify({action:'review',settings:{},edits:[{doc:friday,card:0,id:manager.id,location:''},{doc:friday,card:0,id:server.id,location:''}]}));
const changed=JSON.parse(py.runPython('execute(payload)')).documents[friday].cards[0];
if(!changed.findings.some(f=>f.rule==='Blank location'&&f.rows.includes(server.id)))throw Error('Correction did not recheck server');
if(changed.findings.some(f=>f.rows.includes(manager.id)))throw Error('Manager exemption regressed');
console.log('Browser corrections recheck server locations while exempting Managers.');
