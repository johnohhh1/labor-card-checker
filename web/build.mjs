import fs from 'node:fs/promises';
import path from 'node:path';
const pub='public';
await fs.mkdir(pub+'/runtime',{recursive:true});
await fs.mkdir(pub+'/vendor',{recursive:true});
for(const name of ['pyodide.js','pyodide.asm.js','pyodide.asm.wasm','python_stdlib.zip','pyodide-lock.json'])await fs.copyFile('node_modules/pyodide/'+name,pub+'/runtime/'+name);
const pkg=JSON.parse(await fs.readFile('node_modules/pyodide/package.json','utf8'));
const lock=JSON.parse(await fs.readFile(pub+'/runtime/pyodide-lock.json','utf8'));
const wanted=new Set();
function include(name){if(wanted.has(name))return;wanted.add(name);for(const dep of lock.packages[name].depends)include(dep)}
for(const name of ['micropip','pillow','cryptography'])include(name);
await Promise.all([...wanted].map(async name=>{const file=lock.packages[name].file_name;const response=await fetch(`https://cdn.jsdelivr.net/pyodide/v${pkg.version}/full/${file}`);if(!response.ok)throw Error(file+' '+response.status);await fs.writeFile(pub+'/runtime/'+file,new Uint8Array(await response.arrayBuffer()));console.log(name)}));
const keep=new Set(['pyodide.js','pyodide.asm.js','pyodide.asm.wasm','python_stdlib.zip','pyodide-lock.json',...[...wanted].map(n=>lock.packages[n].file_name)]);
for(const file of await fs.readdir(pub+'/runtime'))if(!keep.has(file))await fs.unlink(path.join(pub,'runtime',file));
for(const name of ['pdf.mjs','pdf.worker.mjs'])await fs.copyFile('node_modules/pdfjs-dist/build/'+name,pub+'/vendor/'+name.replace('.mjs','.js'));
await fs.cp('node_modules/pdfjs-dist/standard_fonts',pub+'/vendor/standard_fonts',{recursive:true});
await fs.copyFile('../local/analyzer.py',pub+'/analyzer.py');
await fs.copyFile('../local/style.css',pub+'/style.css');
let html=await fs.readFile('../local/index.html','utf8');
html=html.replace(/<section class="downloaded">[\s\S]*?<\/section>/,'');
html=html.replace('Your files stay on this computer.','Your files stay in your browser. Nothing is uploaded or stored on the website.');
html=html.replace('<script src="/app.js"></script>','<script type="module" src="/app.js"></script>');
await fs.writeFile(pub+'/index.html',html);
await fs.writeFile(pub+'/wheels.json',JSON.stringify((await fs.readdir(pub+'/wheels')).filter(x=>x.endsWith('.whl'))));
let app=await fs.readFile('../local/app.js','utf8');
app=app.replace(/function currentThursday\(\)[\s\S]*?\$\('week'\).value=currentThursday\(\);\s*/, '');
app=app.replace(/async function request\(url,body\)[\s\S]*?(?=function fileData)/,`async function request(url,body){return JSON.parse(await engineRequest({...body,action:url==='/analyze'?'analyze':'review'}))}\n`);
app=app.replace("$('export').href='/export?session='+encodeURIComponent(review.session);", "$('export').href='#';");
app=app.replace(/\$\('preview'\).src=`\/preview\?[^;]+;/, 'renderPreview(x).catch(e=>{$("preview").alt="Preview unavailable: "+e.message});');
app=app.replace('files:await Promise.all(files.map(fileData)),settings','files:await prepareFiles(files),settings');
app=app.replace("}finally{$('analyze').disabled=false}","}finally{$('analyze').disabled=false}");
await fs.writeFile(pub+'/app.js',(await fs.readFile('browser-ui.js','utf8'))+'\n'+app);
console.log('Built private browser review assets.');
